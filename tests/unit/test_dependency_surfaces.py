"""The dependency surfaces have exactly one authority, and everyone installs it.

RC1 re-froze requirements.lock and requirements/<group>.txt, but the root
requirements.txt and the Dockerfiles kept installing a second, older pin set:
fastapi 0.141.1 / uvicorn 0.52.1 / timm 0.9.2 against the lock's 0.162.0 /
0.54.0 / 1.0.30. requirements.txt also called itself "fully pinned" while holding
floors (python-multipart, pydantic>=, dlib>=, pytest>=, httpx>=, ruff>=).

The hierarchy this file enforces:

* pyproject.toml          - direct dependency source only
* requirements.lock       - the frozen environment snapshot (one platform)
* requirements/<g>.txt    - generated installable deployment groups
* requirements.txt        - generated compatibility entry, identical to runtime
* Dockerfiles / CI        - install the generated groups, never the compat file
"""
import os
import re

import pytest

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def _read(relative: str) -> str:
    with open(os.path.join(PROJECT_ROOT, relative), encoding="utf-8") as handle:
        return handle.read()


def _pins(text: str) -> list[str]:
    return [line.strip() for line in text.splitlines()
            if line.strip() and not line.strip().startswith("#")]


def _lock_pins() -> dict[str, str]:
    pins = {}
    for line in _pins(_read("requirements.lock")):
        name, _, version = line.partition("==")
        pins[name.strip().lower().replace("_", "-").replace(".", "-")] = version.strip()
    return pins


def test_root_requirements_is_a_generated_compatibility_entry_not_a_second_lock():
    """The root file must be generated from the runtime group, byte for byte.

    It used to be hand-maintained: it said "flat, fully pinned list" while carrying
    `python-multipart`, `pydantic>=2.7`, `dlib>=20.0.1`, `pytest>=8.0`, `httpx>=0.27`
    and `ruff>=0.6`, and its fastapi/uvicorn/timm versions had drifted from the lock.
    """
    text = _read("requirements.txt")
    head = "\n".join(text.splitlines()[:14])
    assert "Generated by scripts/export_locks.py" in head, (
        "requirements.txt is not generated; a hand-maintained copy is the drift this gate exists to stop"
    )
    assert "Compatibility entry" in head, (
        "requirements.txt does not say what it is; it used to claim to be the authoritative pinned list"
    )
    assert "requirements/runtime.txt" in head, (
        "requirements.txt does not point at the runtime group it is generated from"
    )
    assert "fully pinned" not in text.lower(), (
        "requirements.txt still claims to be a fully pinned list; the lock is the only freeze"
    )
    assert _pins(text) == _pins(_read("requirements/runtime.txt")), (
        "requirements.txt and requirements/runtime.txt have different pins"
    )


def test_every_generated_file_names_the_platform_it_is_frozen_for():
    """A win32 freeze installed on Linux without a warning is a silent mismatch.

    The group files are a closure over installed wheels (torch +cu128, dlib from a
    conda build), so they are only guaranteed on the platform in the lock header.
    The file must say that, so a reader cannot mistake it for a cross-platform lock.
    """
    files = ["requirements.lock", "requirements.txt"]
    files += [os.path.join("requirements", name)
              for name in sorted(os.listdir(os.path.join(PROJECT_ROOT, "requirements")))]
    for relative in files:
        text = _read(relative)
        assert re.search(r"^# Platform scope: python 3\.11 / \w+$", text, re.MULTILINE), (
            f"{relative} does not state its platform scope"
        )


def _pip_lines(relative: str) -> list[str]:
    body = _read(relative)
    return [line.strip() for line in body.splitlines() if "pip install" in line]


@pytest.mark.parametrize("relative", ["Dockerfile", "docker/api.Dockerfile",
                                      "docker/worker.Dockerfile", "docker/local.Dockerfile"])
def test_every_image_installs_generated_group_files(relative):
    """Images must install the pinned groups, not pyproject floors or the compat file.

    `pip install -e ".[gpu,postgres,redis,s3]"` resolves every floor again and
    produced Pillow 12.3.0 in the worker image while every file said 13.0.0 (P18).
    The project itself must be installed with --no-deps after the groups are in.
    """
    body = _read(relative)
    installs = "\n".join(
        line for line in body.splitlines()
        if "pip install" in line or "-r requirements" in line
    )
    assert re.search(r"-r\s+requirements\.txt", installs) is None, (
        f"{relative} installs the compatibility entry; install requirements/runtime.txt or gpu.txt"
    )
    assert re.search(r"-r\s+requirements/(runtime|gpu)\.txt", installs), (
        f"{relative} does not install a generated deployment group"
    )
    if '-e .[' in body or '-e ".[' in body or "-e '.[" in body:
        assert "--no-deps" in body, (
            f"{relative} installs the project with extras after the lock; that re-resolves floors"
        )


